// Generates every form of the design tokens from src/*.tokens.json.
//
//   node packages/tokens/scripts/generate.ts           write the outputs
//   node packages/tokens/scripts/generate.ts --check   fail if an output is out of date or
//                                                      edited by hand, or a colour pair is
//                                                      below its contrast minimum
//
// Outputs (paths from the kit's root):
//   packages/tokens/generated/theme.css                 daisyUI themes "light" and "dark" + Tailwind theme
//   packages/tokens/generated/tokens.ts                 typed constants
//   packages/tokens/generated/android/values/colors.xml, values-night/colors.xml
//   crates/droid-kit-tokens/src/generated.rs           Rust constants
//   crates/droid-kit-platform/android/src/main/res/values{,-night}/dk_colors.xml
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const KIT_ROOT = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const SRC = join(KIT_ROOT, 'packages/tokens/src');
const EXT = 'com.ortusnova.droidkit';
const HEADER = 'Generated by packages/tokens/scripts/generate.ts from packages/tokens/src/*.tokens.json. Do not edit.';

type Json = Record<string, unknown>;
type Dimension = { value: number; unit: 'px' | 'rem' };
type Color = { colorSpace: string; components: number[]; alpha?: number; hex?: string };

export type Mode = 'light' | 'dark';
export type Role =
  | 'background' | 'surface' | 'surface-sunken' | 'surface-raised' | 'border' | 'control-border'
  | 'text' | 'text-muted' | 'accent' | 'on-accent' | 'accent-text' | 'accent-soft' | 'on-accent-soft'
  | 'success' | 'on-success' | 'warning' | 'on-warning' | 'danger' | 'on-danger' | 'scrim';

export interface Tokens {
  colors: Record<Mode, Record<Role, string>>;
  radius: Record<'selector' | 'field' | 'box', string>;
  size: Record<'selector' | 'field', string>;
  borderWidth: string;
  depth: number;
  noise: number;
  spacingUnit: string;
  touchTargetPx: number;
  fontSans: string[];
  fontSize: Record<'caption' | 'small' | 'body' | 'title' | 'headline', string>;
  fontWeight: Record<'regular' | 'medium' | 'bold', number>;
  duration: Record<'fast' | 'base' | 'slow', number>;
  easing: Record<'standard' | 'out', [number, number, number, number]>;
}

/** The source files, parsed. */
export function readSources(): Record<string, Json> {
  const out: Record<string, Json> = {};
  for (const f of readdirSync(SRC).filter(f => f.endsWith('.tokens.json')).sort()) {
    out[f] = JSON.parse(readFileSync(join(SRC, f), 'utf8')) as Json;
  }
  return out;
}

function at(src: Json, path: string): Json {
  let node: unknown = src;
  for (const k of path.split('.')) {
    node = (node as Json)?.[k];
    if (node === undefined) throw new Error(`token ${path} is missing`);
  }
  return node as Json;
}

const dim = (t: Json) => {
  const v = t.$value as Dimension;
  return `${v.value}${v.unit}`;
};

/** A colour as #rrggbb, or #rrggbbaa when translucent, from its sRGB components (the hex field is only a fallback). */
export function toHex(c: Color): string {
  if (c.colorSpace !== 'srgb') throw new Error(`colour space ${c.colorSpace} is not supported by the generator`);
  const byte = (x: number) => Math.round(x * 255).toString(16).padStart(2, '0');
  const alpha = c.alpha === undefined || c.alpha >= 1 ? '' : byte(c.alpha);
  return '#' + c.components.map(byte).join('') + alpha;
}

/** Android writes alpha first: #aarrggbb. */
function androidHex(hex: string): string {
  return hex.length === 9 ? `#${hex.slice(7)}${hex.slice(1, 7)}` : hex;
}

export function resolve(sources = readSources()): Tokens {
  const color = sources['color.tokens.json'];
  const shape = sources['shape.tokens.json'];
  const space = sources['space.tokens.json'];
  const type = sources['type.tokens.json'];
  const motion = sources['motion.tokens.json'];
  const roles = at(color, 'color');
  const colors = { light: {}, dark: {} } as Tokens['colors'];
  for (const [role, token] of Object.entries(roles)) {
    if (role.startsWith('$')) continue;
    const t = token as Json;
    colors.light[role as Role] = toHex(t.$value as Color);
    const dark = ((t.$extensions as Json)?.[EXT] as Json)?.dark as Color | undefined;
    if (!dark) throw new Error(`color.${role} has no dark value in $extensions["${EXT}"].dark`);
    colors.dark[role as Role] = toHex(dark);
  }
  const ms = (t: Json) => {
    const v = t.$value as { value: number; unit: 'ms' | 's' };
    return v.unit === 's' ? v.value * 1000 : v.value;
  };
  const touch = at(space, 'space.touch-target').$value as Dimension;
  if (touch.unit !== 'px') throw new Error('space.touch-target must be in px');
  return {
    colors,
    radius: { selector: dim(at(shape, 'radius.selector')), field: dim(at(shape, 'radius.field')), box: dim(at(shape, 'radius.box')) },
    size: { selector: dim(at(shape, 'size.selector')), field: dim(at(shape, 'size.field')) },
    borderWidth: dim(at(shape, 'border-width')),
    depth: at(shape, 'depth').$value as number,
    noise: at(shape, 'noise').$value as number,
    spacingUnit: dim(at(space, 'space.unit')),
    touchTargetPx: touch.value,
    fontSans: at(type, 'font.family.sans').$value as string[],
    fontSize: Object.fromEntries(
      ['caption', 'small', 'body', 'title', 'headline'].map(k => [k, dim(at(type, `font.size.${k}`))]),
    ) as Tokens['fontSize'],
    fontWeight: Object.fromEntries(['regular', 'medium', 'bold'].map(k => [k, at(type, `font.weight.${k}`).$value as number])) as Tokens['fontWeight'],
    duration: Object.fromEntries(['fast', 'base', 'slow'].map(k => [k, ms(at(motion, `motion.duration.${k}`))])) as Tokens['duration'],
    easing: Object.fromEntries(['standard', 'out'].map(k => [k, at(motion, `motion.easing.${k}`).$value])) as Tokens['easing'],
  };
}

// ---------------------------------------------------------------- contrast

function luminance(hex: string): number {
  const [r, g, b] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Every pair the design-tokens spec requires, with its minimum ratio. */
export const PAIRS: Array<[fg: Role, bg: Role, min: number]> = [
  ...(['background', 'surface', 'surface-sunken', 'surface-raised'] as Role[]).map(bg => ['text', bg, 4.5] as [Role, Role, number]),
  ...(['background', 'surface', 'surface-raised'] as Role[]).map(bg => ['text-muted', bg, 4.5] as [Role, Role, number]),
  ['on-accent', 'accent', 4.5],
  ['on-accent-soft', 'accent-soft', 4.5],
  ['on-success', 'success', 4.5],
  ['on-warning', 'warning', 4.5],
  ['on-danger', 'danger', 4.5],
  ...(['background', 'surface', 'surface-sunken'] as Role[]).map(bg => ['accent-text', bg, 4.5] as [Role, Role, number]),
  // The accent as a fill (selected checkbox, active segment) is a non-text indicator.
  ['accent', 'surface', 3],
  ['accent', 'background', 3],
  ...(['surface', 'surface-sunken', 'surface-raised'] as Role[]).map(bg => ['control-border', bg, 3] as [Role, Role, number]),
  ['accent', 'surface-sunken', 3],
];

export function contrastProblems(tokens: Tokens): string[] {
  const out: string[] = [];
  for (const mode of ['light', 'dark'] as Mode[]) {
    for (const [fg, bg, min] of PAIRS) {
      const ratio = contrast(tokens.colors[mode][fg], tokens.colors[mode][bg]);
      if (ratio < min) out.push(`${mode}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, below ${min}:1`);
    }
  }
  return out;
}

// ---------------------------------------------------------------- outputs

function themeBlock(t: Tokens, mode: Mode): string {
  const c = t.colors[mode];
  const lines = [
    `  name: "${mode}";`,
    `  default: ${mode === 'light'};`,
    `  prefersdark: false;`,
    `  color-scheme: ${mode};`,
    `  --root-bg: ${c.background};`,
    `  --color-base-100: ${c.surface};`,
    `  --color-base-200: ${c['surface-sunken']};`,
    `  --color-base-300: ${c.border};`,
    `  --color-base-content: ${c.text};`,
    `  --color-primary: ${c.accent};`,
    `  --color-primary-content: ${c['on-accent']};`,
    `  --color-secondary: ${c['accent-soft']};`,
    `  --color-secondary-content: ${c['on-accent-soft']};`,
    `  --color-accent: ${c['on-accent-soft']};`,
    `  --color-accent-content: ${c['accent-soft']};`,
    `  --color-neutral: ${c.text};`,
    `  --color-neutral-content: ${c.background};`,
    `  --color-info: ${c.accent};`,
    `  --color-info-content: ${c['on-accent']};`,
    `  --color-success: ${c.success};`,
    `  --color-success-content: ${c['on-success']};`,
    `  --color-warning: ${c.warning};`,
    `  --color-warning-content: ${c['on-warning']};`,
    `  --color-error: ${c.danger};`,
    `  --color-error-content: ${c['on-danger']};`,
    `  --radius-selector: ${t.radius.selector};`,
    `  --radius-field: ${t.radius.field};`,
    `  --radius-box: ${t.radius.box};`,
    `  --size-selector: ${t.size.selector};`,
    `  --size-field: ${t.size.field};`,
    `  --border: ${t.borderWidth};`,
    `  --depth: ${t.depth};`,
    `  --noise: ${t.noise};`,
    `  --dk-color-background: ${c.background};`,
    `  --dk-color-raised: ${c['surface-raised']};`,
    `  --dk-color-muted: ${c['text-muted']};`,
    `  --dk-color-accent-text: ${c['accent-text']};`,
    `  --dk-color-divider: ${c.border};`,
    `  --dk-color-control: ${c['control-border']};`,
    `  --dk-color-scrim: ${c.scrim};`,
    `  --dk-system-bars: ${c.background};`,
  ];
  return `@plugin "daisyui/theme" {\n${lines.join('\n')}\n}`;
}

export function themeCss(t: Tokens): string {
  const bezier = (b: number[]) => `cubic-bezier(${b.join(', ')})`;
  return `/* ${HEADER} */

/* The two daisyUI themes. The boot script sets <html data-theme="light|dark">. */
${themeBlock(t, 'light')}

${themeBlock(t, 'dark')}

/* Roles daisyUI has no colour for, as Tailwind colours: bg-background,
   bg-raised, bg-scrim, text-muted, text-accent-text, border-divider, border-control. */
@theme inline {
  --color-background: var(--dk-color-background);
  --color-raised: var(--dk-color-raised);
  --color-muted: var(--dk-color-muted);
  --color-accent-text: var(--dk-color-accent-text);
  --color-divider: var(--dk-color-divider);
  --color-control: var(--dk-color-control);
  --color-scrim: var(--dk-color-scrim);
}

/* The scale, as Tailwind theme variables (not inline), so utilities read
   var(--spacing), var(--text-body), ... and a subtree can override them. */
@theme {
  --spacing: ${t.spacingUnit};
  --spacing-touch: ${t.touchTargetPx}px;
  --font-sans: ${t.fontSans.map(f => (/\s/.test(f) ? `"${f}"` : f)).join(', ')};
  --text-caption: ${t.fontSize.caption};
  --text-small: ${t.fontSize.small};
  --text-body: ${t.fontSize.body};
  --text-title: ${t.fontSize.title};
  --text-headline: ${t.fontSize.headline};
  --font-weight-regular: ${t.fontWeight.regular};
  --font-weight-medium: ${t.fontWeight.medium};
  --font-weight-bold: ${t.fontWeight.bold};
  --ease-standard: ${bezier(t.easing.standard)};
  --ease-out: ${bezier(t.easing.out)};
  --default-transition-duration: ${t.duration.base}ms;
  --default-transition-timing-function: ${bezier(t.easing.standard)};
}

:root {
  --dk-duration-fast: ${t.duration.fast}ms;
  --dk-duration-base: ${t.duration.base}ms;
  --dk-duration-slow: ${t.duration.slow}ms;
  --dk-touch-target: ${t.touchTargetPx}px;
}
`;
}

export function tokensTs(t: Tokens): string {
  return `// ${HEADER}\n\nexport const tokens = ${JSON.stringify(t, null, 2)} as const;\n\nexport type ColorRole = keyof typeof tokens.colors.light;\n`;
}

function rustName(s: string): string {
  return s.replace(/-/g, '_').toUpperCase();
}

export function tokensRs(t: Tokens): string {
  const mod = (mode: Mode) =>
    `/// ${mode === 'light' ? 'Light' : 'Dark'} mode colours, \`#rrggbb\`.\npub mod ${mode} {\n` +
    Object.entries(t.colors[mode]).map(([k, v]) => `    pub const ${rustName(k)}: &str = "${v}";`).join('\n') +
    '\n}\n';
  return `// ${HEADER}\n\n${mod('light')}\n${mod('dark')}\n/// Minimum touch target, CSS pixels.\npub const TOUCH_TARGET_PX: u32 = ${t.touchTargetPx};\n`;
}

export function androidColors(t: Tokens, mode: Mode): string {
  const items = Object.entries(t.colors[mode]).map(([k, v]) => `    <color name="dk_${k.replace(/-/g, '_')}">${androidHex(v)}</color>`);
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} -->\n<resources>\n${items.join('\n')}\n</resources>\n`;
}

/** Every output file (path from the kit's root) and its content. */
export function outputs(t: Tokens = resolve()): Map<string, string> {
  return new Map([
    ['packages/tokens/generated/theme.css', themeCss(t)],
    ['packages/tokens/generated/tokens.ts', tokensTs(t)],
    ['packages/tokens/generated/android/values/colors.xml', androidColors(t, 'light')],
    ['packages/tokens/generated/android/values-night/colors.xml', androidColors(t, 'dark')],
    ['crates/droid-kit-tokens/src/generated.rs', tokensRs(t)],
    // The platform plugin's Android library ships the colours, so an app's
    // themes.xml can use @color/dk_background for its window and launch screen.
    ['crates/droid-kit-platform/android/src/main/res/values/dk_colors.xml', androidColors(t, 'light')],
    ['crates/droid-kit-platform/android/src/main/res/values-night/dk_colors.xml', androidColors(t, 'dark')],
  ]);
}

/** Outputs whose file on disk differs from what the source produces. */
export function staleOutputs(expected: Map<string, string>, read: (path: string) => string | null): string[] {
  return [...expected].filter(([path, content]) => read(path) !== content).map(([path]) => path);
}

function readOrNull(path: string): string | null {
  try {
    return readFileSync(join(KIT_ROOT, path), 'utf8');
  } catch {
    return null;
  }
}

function main(): number {
  const check = process.argv.includes('--check');
  const tokens = resolve();
  const files = outputs(tokens);
  const problems = contrastProblems(tokens);
  if (check) {
    for (const path of staleOutputs(files, readOrNull)) {
      problems.push(`${path} does not match the token source: it was edited by hand, or the generator was not run`);
    }
  } else {
    for (const [path, content] of files) {
      mkdirSync(dirname(join(KIT_ROOT, path)), { recursive: true });
      writeFileSync(join(KIT_ROOT, path), content);
    }
  }
  for (const p of problems) console.error(`problem: ${p}`);
  if (problems.length === 0) console.error(check ? 'ok: tokens are up to date and pass contrast' : `wrote ${files.size} files`);
  return problems.length === 0 ? 0 : 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main();
